/* ── 8. PRICE HISTORY & AI AGMARKNET FORECAST DATA ───────────────────────── */
export function generateMockPriceHistory(days = 30) {
  const result = [];
  const now = new Date();
  const crops = [
    { type: 'mustard', base: 5950, trend: 15, variance: 80 },
    { type: 'soyabean', base: 4850, trend: 8, variance: 60 },
    { type: 'groundnut', base: 7100, trend: 18, variance: 95 },
    { type: 'sunflower', base: 5800, trend: 10, variance: 70 },
  ];

  for (let i = days; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];

    crops.forEach(c => {
      const dayProgress = (days - i) / days;
      const seasonal = Math.sin((i / 7) * Math.PI) * c.variance;
      const price = Math.round(c.base + (dayProgress * c.trend * 20) + seasonal);
      result.push({
        crop_type: c.type,
        price_per_quintal: price,
        recorded_date: dateStr,
      });
    });
  }
  return result;
}

export function generateMockPriceChartData(days = 30) {
  const raw = generateMockPriceHistory(days);
  const byDate = {};
  raw.forEach(row => {
    const d = row.recorded_date;
    if (!byDate[d]) byDate[d] = { date: d, prices: {} };
    const ct = row.crop_type || 'other';
    if (!byDate[d].prices[ct]) byDate[d].prices[ct] = [];
    byDate[d].prices[ct].push(Number(row.price_per_quintal));
  });

  return Object.values(byDate).map(entry => {
    const row = {
      date: new Date(entry.date).toLocaleDateString('en-IN', { day: 'numeric', month: 'short' }),
    };
    Object.entries(entry.prices).forEach(([crop, vals]) => {
      row[crop] = Math.round(vals.reduce((a, b) => a + b, 0) / vals.length);
    });
    return row;
  });
}

